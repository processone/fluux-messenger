"""FLM-377: opt-in structural observer for the Web Inspector byte stream.

StructureTap wraps the exclusive stream given to Reader. It forwards every call
unchanged and reduces each complete inbound/outbound frame to allowlisted names,
type tags, counts and sizes. It never keeps a title, URL, text, identifier, bundle
of another app, console message, evaluated value or raw frame after describing it.

Reader stays the only protocol actor: the tap sends nothing, cannot change what
Reader receives, and swallows its own decoding failures. Its report is output
charged to the attempt's shared Budget before an entry is kept.
"""

import json
import plistlib
import re
import struct

from reader import BUNDLE, PRESENT, REMOVE, SAMPLE, SAMPLER

MAX_ENTRIES = 128
# Room for later repeat/maxBytes updates, charged once when an entry is kept.
ENTRY_SLACK = 32

SELECTORS = frozenset({
    "_rpc_reportIdentifier:", "_rpc_getConnectedApplications:", "_rpc_forwardGetListing:",
    "_rpc_forwardSocketSetup:", "_rpc_forwardSocketData:", "_rpc_forwardDidClose:",
    "_rpc_forwardIndicateWebView:", "_rpc_requestApplicationLaunch:",
    "_rpc_forwardAutomationSessionRequest:", "_rpc_forwardAutomaticInspectionConfiguration:",
    "_rpc_forwardAutomaticInspectionRejection:",
    "_rpc_reportCurrentState:", "_rpc_reportConnectedApplicationList:",
    "_rpc_reportConnectedDriverList:", "_rpc_applicationSentListing:", "_rpc_applicationUpdated:",
    "_rpc_applicationConnected:", "_rpc_applicationSentData:", "_rpc_applicationDisconnected:",
    "_rpc_reportAutomaticInspectionCandidate:", "_rpc_reportSetup:"})
# WebKit's remote inspector protocol names live in these namespaces. Argument and
# entry keys are generated by webinspectord/WebKit, never by page content; keys of
# identifier-indexed maps (applications, listings, drivers) are only counted.
SELECTOR_FORM = re.compile(r"_rpc_[A-Za-z]{1,80}:\Z")
WIR_FORM = re.compile(r"WIR[A-Z][A-Za-z]{0,62}\Z")
JSON_KEY_FORM = re.compile(r"[a-z][A-Za-z]{0,40}\Z")
METHOD_FORM = re.compile(r"[A-Z][A-Za-z]{0,40}\.[a-z][A-Za-z]{0,60}\Z")
WEBKIT_BUNDLES = frozenset({BUNDLE, "com.apple.WebKit.WebContent", "com.apple.WebKit.Networking",
                            "com.apple.WebKit.GPU"})
TARGET_TYPES = frozenset({"page", "frame", "worker", "service-worker", "javascript"})
REMOTE_TYPES = frozenset({"undefined", "boolean", "number", "string", "object", "function",
                          "symbol", "bigint"})
REMOTE_SUBTYPES = frozenset({"null", "array", "node", "regexp", "date", "error", "map", "set",
                             "weakmap", "weakset", "iterator", "class", "proxy"})
FLAGS = ("WIRIsApplicationProxyKey", "WIRIsApplicationReadyKey", "WIRIsApplicationActiveKey")
NEVER = re.compile(r"(?!)")
DECODE_FAULTS = frozenset({"InvalidFileException", "JSONDecodeError", "UnicodeDecodeError", "ValueError",
                           "TypeError", "KeyError", "AttributeError", "RecursionError", "OverflowError",
                           "error"})
EXPRESSIONS = {PRESENT: "present", SAMPLER: "install", SAMPLE: "sample", REMOVE: "remove"}
# Words of the report's own schema (keys and fixed labels).
SCHEMA = frozenset({
    "messages", "omitted", "truncated", "partial", "observerFault", "dir", "in", "out", "bytes",
    "received", "maxBytes", "repeat", "selector", "arg", "otherKeys", "unknownKeys", "decode",
    "apps", "count", "nonDict", "fluux", "proxies", "hostedByFluux", "hostedBundles",
    "identifierMismatch", "keys", "fluuxEntries", "hostedEntries", "entry", "identifierForm", "pid", "flags", "forFluux",
    "pages", "types", "pageIdTypes", "listingKeyMismatch", "destination", "sender", "absent",
    "dataType", "data", "method", "params", "targetInfo", "type", "subtype", "isProvisional",
    "inner", "result", "remote", "valueType", "wasThrown", "error", "expression", "drivers", "other",
    "present", "install", "sample", "remove", "str", "int", "float", "bool", "bytes", "dict",
    "list", "null", "date", "uid"})
LABELS = (frozenset(EXPRESSIONS.values()) | WEBKIT_BUNDLES | TARGET_TYPES | REMOTE_TYPES | REMOTE_SUBTYPES
          | DECODE_FAULTS)


def kind(value):
    """A type tag only; the value itself is never inspected further here."""
    if value is None:
        return "null"
    if type(value) is bool:
        return "bool"
    for tag, types in (("int", int), ("float", float), ("str", str), ("bytes", (bytes, bytearray)),
                       ("dict", dict), ("list", list)):
        if isinstance(value, types):
            return tag
    name = type(value).__name__
    return "date" if name == "datetime" else "uid" if name == "UID" else "other"


def name(value, known, form):
    return value if type(value) is str and (value in known or form.fullmatch(value)) else "other"


def shape(mapping, form):
    """Protocol key presence and type tags; unknown key names stay a count."""
    keys, other = {}, 0
    for key, value in mapping.items():
        if type(key) is str and form.fullmatch(key):
            keys[key] = kind(value)
        else:
            other += 1
    return {"keys": keys, "otherKeys": other}


def tally(entries, form):
    """Aggregate entry shapes as key -> type -> count."""
    keys, other = {}, 0
    for entry in entries:
        for key, value in entry.items():
            if type(key) is str and form.fullmatch(key):
                counts = keys.setdefault(key, {})
                counts[kind(value)] = counts.get(kind(value), 0) + 1
            else:
                other += 1
    return {"keys": keys, "otherKeys": other}


def flag(value):
    if type(value) is bool or (type(value) is int and 0 <= value <= 9):
        return value
    return kind(value)


class Describer:
    """Turns decoded frames into sanitized entries. Remote identities seen here are
    held in memory only to label messages as Fluux's; they are never reported."""

    def __init__(self):
        self.fluux = set()
        self.sender = None

    def entry(self, app):
        identity = app.get("WIRApplicationIdentifierKey")
        described = shape(app, WIR_FORM)
        described["identifierForm"] = ("pid" if type(identity) is str and re.fullmatch(r"PID:[0-9]{1,10}", identity)
                                       else kind(identity))
        described["flags"] = {key: flag(app[key]) for key in FLAGS if key in app}
        return described

    def applications(self, apps):
        values = [app for app in apps.values() if type(app) is dict]
        for app in values:
            if app.get("WIRApplicationBundleIdentifierKey") == BUNDLE:
                identity = app.get("WIRApplicationIdentifierKey")
                if type(identity) is str:
                    self.fluux.add(identity)
        fluux = [app for app in values if app.get("WIRApplicationBundleIdentifierKey") == BUNDLE]
        hosted = [app for app in values if app.get("WIRHostApplicationIdentifierKey") in self.fluux]
        bundles = {}
        for app in hosted:
            label = name(app.get("WIRApplicationBundleIdentifierKey"), WEBKIT_BUNDLES, NEVER)
            bundles[label] = bundles.get(label, 0) + 1
        return dict(tally(values, WIR_FORM), **{
            "count": len(apps), "nonDict": len(apps) - len(values), "fluux": len(fluux),
            "proxies": sum(app.get("WIRIsApplicationProxyKey") is True for app in values),
            "hostedByFluux": len(hosted), "hostedBundles": bundles,
            "identifierMismatch": sum(key != app.get("WIRApplicationIdentifierKey")
                                      for key, app in apps.items() if type(app) is dict),
            "fluuxEntries": [self.entry(app) for app in fluux[:2]],
            "hostedEntries": [self.entry(app) for app in hosted[:2]]})

    def remote(self, value):
        described = shape(value, JSON_KEY_FORM)
        described["type"] = name(value.get("type"), REMOTE_TYPES, NEVER)
        if "subtype" in value:
            described["subtype"] = name(value.get("subtype"), REMOTE_SUBTYPES, NEVER)
        if "value" in value:
            described["valueType"] = kind(value["value"])
        return described

    def message(self, message, depth=0):
        if type(message) is not dict:
            return {"type": kind(message)}
        described = shape(message, JSON_KEY_FORM)
        if "method" in message:
            described["method"] = name(message["method"], (), METHOD_FORM)
        params = message.get("params")
        if type(params) is dict:
            described["params"] = shape(params, JSON_KEY_FORM)
            info = params.get("targetInfo")
            if type(info) is dict:
                described["targetInfo"] = dict(shape(info, JSON_KEY_FORM),
                                               type=name(info.get("type"), TARGET_TYPES, NEVER))
                if type(info.get("isProvisional")) is bool:
                    described["targetInfo"]["isProvisional"] = info["isProvisional"]
            if depth == 0 and message.get("method") == "Target.dispatchMessageFromTarget":
                described["inner"] = self.json(params.get("message"), depth + 1)
        result = message.get("result")
        if type(result) is dict:
            described["result"] = shape(result, JSON_KEY_FORM)
            if type(result.get("result")) is dict:
                described["result"]["remote"] = self.remote(result["result"])
            if type(result.get("wasThrown")) is bool:
                described["result"]["wasThrown"] = result["wasThrown"]
        error = message.get("error")
        if type(error) is dict:
            described["error"] = shape(error, JSON_KEY_FORM)
        return described

    def json(self, data, depth=0):
        if type(data) not in (str, bytes, bytearray):
            return {"dataType": kind(data)}
        try:
            return self.message(json.loads(data), depth)
        except Exception as error:
            return {"decode": decode_fault(error)}

    def inbound(self, selector, arg):
        described = {}
        if selector == "_rpc_reportConnectedApplicationList:":
            apps = arg.get("WIRApplicationDictionaryKey")
            described["apps"] = self.applications(apps) if type(apps) is dict else {"type": kind(apps)}
        elif selector in ("_rpc_applicationConnected:", "_rpc_applicationUpdated:",
                          "_rpc_applicationDisconnected:"):
            if selector != "_rpc_applicationDisconnected:" and arg.get("WIRApplicationBundleIdentifierKey") == BUNDLE:
                identity = arg.get("WIRApplicationIdentifierKey")
                if type(identity) is str:
                    self.fluux.add(identity)
            described["forFluux"] = arg.get("WIRApplicationIdentifierKey") in self.fluux
            if described["forFluux"]:
                described["entry"] = self.entry(arg)
        elif selector == "_rpc_reportConnectedDriverList:":
            drivers = arg.get("WIRDriverDictionaryKey")
            if type(drivers) is dict:
                described["drivers"] = {"count": len(drivers)}
        elif selector == "_rpc_applicationSentListing:":
            described["forFluux"] = arg.get("WIRApplicationIdentifierKey") in self.fluux
            listing = arg.get("WIRListingKey")
            if described["forFluux"] and type(listing) is dict:
                pages = [page for page in listing.values() if type(page) is dict]
                types, ids = {}, {}
                for page in pages:
                    label = name(page.get("WIRTypeKey"), (), WIR_FORM)
                    types[label] = types.get(label, 0) + 1
                    tag = kind(page.get("WIRPageIdentifierKey")) if "WIRPageIdentifierKey" in page else "absent"
                    ids[tag] = ids.get(tag, 0) + 1
                described["pages"] = dict(tally(pages, WIR_FORM), **{
                    "count": len(listing), "nonDict": len(listing) - len(pages), "types": types,
                    "pageIdTypes": ids,
                    "listingKeyMismatch": sum(str(key) != str(page.get("WIRPageIdentifierKey"))
                                              for key, page in listing.items() if type(page) is dict)})
            elif described["forFluux"]:
                described["pages"] = {"type": kind(listing)}
        elif selector == "_rpc_applicationSentData:":
            described["forFluux"] = arg.get("WIRApplicationIdentifierKey") in self.fluux
            destination = arg.get("WIRDestinationKey")
            described["destination"] = ("absent" if "WIRDestinationKey" not in arg
                                        else "sender" if self.sender is not None and destination == self.sender
                                        else "other")
            described["data"] = self.json(arg.get("WIRMessageDataKey"))
        return described

    def outbound(self, selector, arg):
        described = {}
        if selector == "_rpc_forwardSocketSetup:" and type(arg.get("WIRSenderKey")) is str:
            self.sender = arg["WIRSenderKey"]
        if selector == "_rpc_forwardSocketData:":
            try:
                wrapped = json.loads(arg["WIRSocketDataKey"])
                command = (json.loads(wrapped["params"]["message"])
                           if wrapped.get("method") == "Target.sendMessageToTarget" else wrapped)
                described["expression"] = EXPRESSIONS.get(command["params"]["expression"], "other")
            except Exception:
                described["expression"] = "other"
        return described

    def frame(self, direction, payload):
        entry = {"dir": direction, "bytes": len(payload)}
        try:
            value = plistlib.loads(bytes(payload))
        except Exception as error:
            entry["decode"] = decode_fault(error)
            return entry
        if type(value) is not dict:
            entry["type"] = kind(value)
            return entry
        selector = value.get("__selector")
        entry["selector"] = name(selector, SELECTORS, SELECTOR_FORM)
        arg = value.get("__argument")
        if type(arg) is not dict:
            entry["arg"] = {"type": kind(arg)} if "__argument" in value else {"type": "absent"}
            return entry
        entry["arg"] = shape(arg, WIR_FORM)
        try:
            entry.update(self.inbound(selector, arg) if direction == "in" else self.outbound(selector, arg))
        except Exception as error:
            entry["decode"] = decode_fault(error)
        return entry


def decode_fault(error):
    label = type(error).__name__
    return label if label in DECODE_FAULTS else "other"


class Frames:
    """Reassembles one direction's length-prefixed frames as bytes pass through."""

    def __init__(self, direction, tap):
        self.direction, self.tap = direction, tap
        self.buffer = bytearray()
        self.failed = False

    def feed(self, data):
        if self.failed:
            return
        try:
            self.buffer.extend(data)
            while len(self.buffer) >= 4:
                size = struct.unpack(">I", self.buffer[:4])[0]
                if len(self.buffer) < 4 + size:
                    break
                payload = self.buffer[4:4 + size]
                del self.buffer[:4 + size]
                self.tap.keep(self.tap.describer.frame(self.direction, payload))
                payload[:] = b""
        except Exception as error:
            self.failed = True
            self.buffer.clear()
            self.tap.observer_fault = decode_fault(error)

    def partial(self):
        if len(self.buffer) < 4:
            return {"dir": self.direction, "bytes": None, "received": len(self.buffer)} if self.buffer else None
        return {"dir": self.direction, "bytes": struct.unpack(">I", self.buffer[:4])[0],
                "received": len(self.buffer) - 4}


class StructureTap:
    """Socket-compatible pass-through with the same subset Reader uses.

    Exceptions from the wrapped stream propagate unchanged. Observer failures,
    including a shared Budget refusal, stop observation and never reach Reader.
    """

    def __init__(self, stream, budget, *, limit=MAX_ENTRIES):
        if type(limit) is not int or not 0 < limit <= MAX_ENTRIES:
            raise ValueError("invalid-structure-limit")
        self._stream, self._budget, self._limit = stream, budget, limit
        self.describer = Describer()
        self._inbound, self._outbound = Frames("in", self), Frames("out", self)
        self.messages = []
        self.omitted = 0
        self.truncated = False
        self.observer_fault = None

    def keep(self, entry):
        if self.messages:
            last = self.messages[-1]
            if ({k: v for k, v in last.items() if k not in ("bytes", "maxBytes", "repeat")}
                    == {k: v for k, v in entry.items() if k != "bytes"}):
                last["repeat"] = last.get("repeat", 1) + 1
                last["maxBytes"] = max(last.get("maxBytes", last["bytes"]), entry["bytes"])
                return
        if self.truncated or len(self.messages) >= self._limit:
            self.omitted += 1
            return
        try:
            self._budget.charge(len(json.dumps(entry, separators=(",", ":"))) + ENTRY_SLACK, output=True)
        except Exception:
            self.truncated = True
            self.omitted += 1
            return
        self.messages.append(entry)

    def settimeout(self, seconds):
        return self._stream.settimeout(seconds)

    def recv(self, size):
        data = self._stream.recv(size)
        self._inbound.feed(data)
        return data

    def send(self, data):
        sent = self._stream.send(data)
        if type(sent) is int and sent > 0:
            self._outbound.feed(memoryview(data).cast("B")[:sent])
        return sent

    def shutdown(self, how):
        return self._stream.shutdown(how)

    def close(self):
        return self._stream.close()

    def __enter__(self):
        return self

    def __exit__(self, *args):
        self.close()

    def report(self):
        """Sanitized entries only; partial frames report sizes, never bytes."""
        partial = [p for p in (self._inbound.partial(), self._outbound.partial()) if p]
        return {"messages": [dict(m) for m in self.messages], "omitted": self.omitted,
                "truncated": self.truncated, "partial": partial, "observerFault": self.observer_fault}


def assert_sanitized(value):
    """Defense in depth before persisting. Keys are schema words, labels or protocol
    key names; string values are schema words, fixed labels, selectors or inspector
    method names, never free-form words. Numbers are counts, sizes or flags."""
    if type(value) is dict:
        for key, item in value.items():
            if type(key) is not str or not (key in SCHEMA or key in LABELS or WIR_FORM.fullmatch(key)
                                             or JSON_KEY_FORM.fullmatch(key)):
                raise ValueError("unsanitized-structure")
            assert_sanitized(item)
    elif type(value) is list:
        for item in value:
            assert_sanitized(item)
    elif type(value) is str:
        if not (value in SCHEMA or value in LABELS or value in SELECTORS
                or SELECTOR_FORM.fullmatch(value) or METHOD_FORM.fullmatch(value)):
            raise ValueError("unsanitized-structure")
    elif value is not None and type(value) not in (bool, int):
        raise ValueError("unsanitized-structure")
