import { readFileSync } from 'node:fs'
import { describe, it, expect } from 'vitest'
import type { XMLElementData } from '@fluux/sdk'
import { createMockPluginContext, seedPeer } from './testing/MockPluginContext'
import { readOwnDeviceLists, removeOwnDevices, addOwnOmemo2Device, type OwnPepAccess } from './deviceLists'
import { parseXml, elementToData } from './stanzaData'
import { NS_DEVICES, NS_BUNDLES, NS_LEGACY_DEVICELIST, NS_LEGACY_BUNDLES_PREFIX } from './namespaces'

const ME = 'me@example.org'

// Device lists and bundles serialized by the reference python-omemo stack (Twomemo 2.1.0 and Oldmemo 2.1.0),
// generated by fixtures/generate_own_devices.py. The reference writes prefixed XML (`ns0:`), which is the
// shape other clients' lists really take. OMEMO 2 devices carry signed labels; the legacy serializer has none.
interface Fixture { omemo2: Side; legacy: Side }
interface Side { devices: string; bundles: Record<string, string>; fingerprints: Record<string, string> }
const fixture = JSON.parse(readFileSync(new URL('./fixtures/own_devices.json', import.meta.url), 'utf8')) as Fixture
const data = (xml: string): XMLElementData => elementToData(parseXml(xml))
const ids = (side: Side): number[] => Object.keys(side.bundles).map(Number)
const sortedIds = (devs: { id: number }[]): number[] => devs.map((d) => d.id).sort((a, b) => a - b)

interface Options { omit?: (protocol: 'omemo2' | 'legacy', id: number) => boolean }
function setup({ omit }: Options = {}) {
  const { ctx, net, publishes } = createMockPluginContext(ME)
  const pep: OwnPepAccess = {
    query: (jid, node, max) => ctx.xmpp.queryPEP(jid, node, max),
    publish: (n, i, o) => ctx.xmpp.publishPEP(n, i, o),
  }
  seedPeer(net, ME, NS_DEVICES, data(fixture.omemo2.devices))
  seedPeer(net, ME, NS_LEGACY_DEVICELIST, data(fixture.legacy.devices))
  for (const [id, bundle] of Object.entries(fixture.omemo2.bundles)) {
    if (!omit?.('omemo2', Number(id))) seedPeer(net, ME, NS_BUNDLES, data(bundle), id)
  }
  for (const [id, bundle] of Object.entries(fixture.legacy.bundles)) {
    if (!omit?.('legacy', Number(id))) seedPeer(net, ME, `${NS_LEGACY_BUNDLES_PREFIX}${id}`, data(bundle), 'current')
  }
  return { pep, net, publishes }
}
type Net = ReturnType<typeof setup>['net']
const stored = (net: Net, node: string): XMLElementData => net.nodes.get(`${ME} ${node}`)![0].payload
const devicesOf = (el: XMLElementData): XMLElementData[] => el.children.filter((c): c is XMLElementData => typeof c !== 'string')

describe('own OMEMO device lists, from reference-client lists and bundles', () => {
  it('reads both lists with labels and identity-key fingerprints', async () => {
    const { pep } = setup()
    const lists = await readOwnDeviceLists(pep, ME)
    if (!lists.omemo2.ok || !lists.legacy.ok) throw new Error('lists should read')
    expect(sortedIds(lists.omemo2.devices)).toEqual(ids(fixture.omemo2).sort((a, b) => a - b))
    expect(lists.omemo2.devices.map((d) => d.label).filter(Boolean).sort()).toEqual(['Laptop', 'Phone'])
    for (const d of lists.omemo2.devices) expect(d.fingerprint).toBe(fixture.omemo2.fingerprints[d.id])
    expect(sortedIds(lists.legacy.devices)).toEqual(ids(fixture.legacy).sort((a, b) => a - b))
    // The reference computed the Curve25519 form itself, so both protocols are checked against it, not our code.
    for (const d of lists.legacy.devices) expect(d.fingerprint).toBe(fixture.legacy.fingerprints[d.id])
  })

  it('keeps a device listed when its bundle is missing or unreadable', async () => {
    const [missingOmemo2] = ids(fixture.omemo2)
    const [missingLegacy, garbled] = ids(fixture.legacy)
    const { pep, net } = setup({ omit: (p, id) => (p === 'omemo2' ? id === missingOmemo2 : id === missingLegacy) })
    seedPeer(net, ME, `${NS_LEGACY_BUNDLES_PREFIX}${garbled}`, data("<bundle xmlns='eu.siacs.conversations.axolotl'><identityKey>!!</identityKey></bundle>"), 'current')
    const lists = await readOwnDeviceLists(pep, ME)
    if (!lists.omemo2.ok || !lists.legacy.ok) throw new Error('lists should read')
    expect(lists.omemo2.devices).toHaveLength(3)
    expect(lists.omemo2.devices.find((d) => d.id === missingOmemo2)!.fingerprint).toBeUndefined()
    expect(lists.omemo2.devices.filter((d) => d.fingerprint)).toHaveLength(2)
    expect(lists.legacy.devices.map((d) => d.fingerprint)).toEqual([undefined, undefined])
  })

  it('keeps the list when the bundle read itself fails', async () => {
    const { pep } = setup()
    const failing: OwnPepAccess = {
      publish: pep.publish,
      query: (jid, node, max) => (node === NS_BUNDLES ? Promise.reject(new Error('service-unavailable')) : pep.query(jid, node, max)),
    }
    const lists = await readOwnDeviceLists(failing, ME)
    expect(lists.omemo2.ok && lists.omemo2.devices.every((d) => d.fingerprint === undefined)).toBe(true)
  })

  it('reads an account with no lists as empty', async () => {
    const { ctx } = createMockPluginContext(ME)
    const lists = await readOwnDeviceLists({ query: (j, n, m) => ctx.xmpp.queryPEP(j, n, m), publish: async () => {} }, ME)
    expect(lists).toEqual({ omemo2: { ok: true, devices: [] }, legacy: { ok: true, devices: [] } })
  })

  it('treats item-not-found as an absent list and any other failure as an error for that list only', async () => {
    const { pep } = setup()
    const failing: OwnPepAccess = {
      publish: pep.publish,
      query: (_jid, node) => Promise.reject(new Error(node === NS_DEVICES ? 'item-not-found' : 'service-unavailable')),
    }
    const lists = await readOwnDeviceLists(failing, ME)
    expect(lists.omemo2).toEqual({ ok: true, devices: [] })
    expect(lists.legacy.ok).toBe(false)
  })

  it('removes a prefixed OMEMO 2 device and leaves the others exactly as published', async () => {
    const { pep, net, publishes } = setup()
    const before = stored(net, NS_DEVICES)
    const [gone, ...rest] = devicesOf(before)
    const result = await removeOwnDevices(pep, ME, 'omemo2', [Number(gone.attrs.id)])
    expect(result).toEqual({ removed: [Number(gone.attrs.id)], missing: [] })
    const after = stored(net, NS_DEVICES)
    expect(after.name).toBe(before.name)
    expect(after.attrs).toEqual(before.attrs)
    expect(devicesOf(after)).toEqual(rest)
    expect(publishes).toHaveLength(1)
    expect(stored(net, NS_LEGACY_DEVICELIST)).toEqual(data(fixture.legacy.devices))
  })

  it('removes a prefixed legacy device', async () => {
    const { pep, net } = setup()
    const [gone, kept] = devicesOf(stored(net, NS_LEGACY_DEVICELIST))
    await removeOwnDevices(pep, ME, 'legacy', [Number(gone.attrs.id)])
    expect(devicesOf(stored(net, NS_LEGACY_DEVICELIST))).toEqual([kept])
  })

  it('does not remove an unrelated extension that is also called device', async () => {
    const { pep, net } = setup()
    const list = stored(net, NS_DEVICES)
    const target = devicesOf(list)[0]
    const foreign: XMLElementData = { name: 'device', attrs: { xmlns: 'urn:example:other', id: target.attrs.id }, children: [] }
    seedPeer(net, ME, NS_DEVICES, { ...list, children: [...list.children, foreign] })
    await removeOwnDevices(pep, ME, 'omemo2', [Number(target.attrs.id)])
    expect(devicesOf(stored(net, NS_DEVICES))).toContainEqual(foreign)
    expect(devicesOf(stored(net, NS_DEVICES)).filter((d) => d.attrs.id === target.attrs.id)).toEqual([foreign])
  })

  it('removes a device from a list that uses the default namespace', async () => {
    const { pep, net } = setup()
    seedPeer(net, ME, NS_DEVICES, data("<devices xmlns='urn:xmpp:omemo:2'><device id='1' label='A'/><device id='2' label='B' x='y'/></devices>"))
    await removeOwnDevices(pep, ME, 'omemo2', [1])
    expect(stored(net, NS_DEVICES)).toEqual(data("<devices xmlns='urn:xmpp:omemo:2'><device id='2' label='B' x='y'/></devices>"))
  })

  it('publishes nothing when the id is not in the list', async () => {
    const { pep, publishes } = setup()
    expect(await removeOwnDevices(pep, ME, 'omemo2', [999])).toEqual({ removed: [], missing: [999] })
    expect(publishes).toHaveLength(0)
  })

  it('refuses a malformed payload without rewriting it', async () => {
    const { pep, net, publishes } = setup()
    seedPeer(net, ME, NS_DEVICES, data("<wrong xmlns='urn:xmpp:omemo:2'><device id='1'/></wrong>"))
    await expect(removeOwnDevices(pep, ME, 'omemo2', [1])).rejects.toThrow(/unexpected/)
    seedPeer(net, ME, NS_DEVICES, data("<devices xmlns='urn:example:other'><device id='1'/></devices>"))
    await expect(removeOwnDevices(pep, ME, 'omemo2', [1])).rejects.toThrow(/unexpected/)
    expect(publishes).toHaveLength(0)
  })

  it('keeps a device another client added after the screen loaded', async () => {
    const { pep, net } = setup()
    await readOwnDeviceLists(pep, ME)
    seedPeer(net, ME, NS_DEVICES, data("<devices xmlns='urn:xmpp:omemo:2'><device id='111'/><device id='777' label='New'/></devices>"))
    await removeOwnDevices(pep, ME, 'omemo2', [111])
    expect((await readOwnDeviceLists(pep, ME)).omemo2).toEqual({ ok: true, devices: [{ id: 777, label: 'New' }] })
  })
})

describe('adding our own device to a list other clients wrote', () => {
  it('keeps every other device entry, signed labels included, and adds ours once', async () => {
    const { pep, net } = setup()
    const before = devicesOf(stored(net, NS_DEVICES))
    await addOwnOmemo2Device(pep, ME, 4242)
    const after = stored(net, NS_DEVICES)
    expect(devicesOf(after).slice(0, before.length)).toEqual(before)
    expect(devicesOf(after)).toHaveLength(before.length + 1)
    const readBack = await readOwnDeviceLists(pep, ME)
    expect(readBack.omemo2.ok && readBack.omemo2.devices.map((d) => d.id)).toContain(4242)
    const publishedCount = net.nodes.get(`${ME} ${NS_DEVICES}`)!.length
    await addOwnOmemo2Device(pep, ME, 4242)
    expect(net.nodes.get(`${ME} ${NS_DEVICES}`)!.length).toBe(publishedCount)
    expect(devicesOf(stored(net, NS_DEVICES))).toEqual(devicesOf(after))
  })

  it('creates the list when there is none', async () => {
    const { ctx } = createMockPluginContext(ME)
    const pep: OwnPepAccess = { query: (j, n, m) => ctx.xmpp.queryPEP(j, n, m), publish: (n, i, o) => ctx.xmpp.publishPEP(n, i, o) }
    await addOwnOmemo2Device(pep, ME, 7)
    expect(await readOwnDeviceLists(pep, ME)).toMatchObject({ omemo2: { ok: true, devices: [{ id: 7 }] } })
  })
})
