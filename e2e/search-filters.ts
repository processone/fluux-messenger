import { test, expect } from '@playwright/test'
import { bootDemo } from './harness/demoBoot'

for (const viewport of [{ width: 1280, height: 800 }, { width: 390, height: 844 }]) {
  test.describe(`search at ${viewport.width}px`, () => {
    test.use({ viewport, locale: 'fr-FR' })
    test('Filters drafts apply as chips, preserve text, and dismiss with keyboard focus intact', async ({ page }) => {
      await bootDemo(page, '/demo.html?tutorial=false')
      await page.locator('[data-nav="search"]').click()
      const input = page.getByRole('combobox')
      await expect(input).toBeVisible()
      const filters = page.getByRole('button', { name: 'Filtres', exact: true })
      await expect(filters).toBeVisible()
      await expect(page.getByRole('button', { name: 'Images', exact: true })).toHaveCount(0)
      await input.fill('design')
      await filters.click()
      const dialog = page.getByRole('dialog', { name: 'Filtres' })
      await expect(dialog).toBeVisible()
      await dialog.getByRole('checkbox', { name: 'Images', exact: true }).check()
      await page.keyboard.press('Escape')
      await expect(dialog).toHaveCount(0)
      await expect(input).toHaveValue('design')
      await expect(input).toBeFocused()
      await expect(page.getByRole('button', { name: 'Retirer Avec une image' })).toHaveCount(0)

      await filters.click()
      await expect(dialog.getByRole('checkbox', { name: 'Images', exact: true })).not.toBeChecked()
      await dialog.getByLabel('Date', { exact: true }).selectOption('custom')
      await dialog.getByLabel('Premier jour').fill('2024-04-01')
      await dialog.getByLabel('Dernier jour').fill('2024-03-31')
      await expect(dialog.getByRole('alert')).toBeVisible()
      await expect(dialog.getByRole('button', { name: 'Appliquer' })).toBeDisabled()
      await dialog.getByLabel('Premier jour').fill('2024-03-01')
      await dialog.getByRole('checkbox', { name: 'Images', exact: true }).check()
      await dialog.getByRole('button', { name: 'De Tout le monde', exact: true }).click()
      await dialog.getByRole('option', { name: 'Moi', exact: true }).click()
      await dialog.getByRole('button', { name: 'Appliquer' }).click()
      await expect(dialog).toHaveCount(0)
      await expect(input).toHaveValue('design')
      await expect(page.getByRole('button', { name: 'Retirer Envoyés par moi' })).toBeVisible()
      await page.getByRole('button', { name: 'Retirer Envoyés par moi' }).click()
      await expect(page.getByRole('button', { name: 'Retirer Avec une image' })).toBeVisible()
      await page.getByRole('button', { name: 'Retirer Avec une image' }).click()
      await expect(input).toHaveValue('design')

      await input.fill('notes from:')
      const person = page.getByRole('option').filter({ hasText: ' · ' }).first()
      await expect(person).toBeVisible()
      await person.click()
      await expect(input).toHaveValue('notes')
      await expect(page.getByRole('button', { name: /^Retirer De / })).toBeVisible()

      await input.fill('fr')
      await expect(input).toHaveAttribute('aria-expanded', 'false')
      await input.fill('has:')
      await expect(input).toHaveAttribute('aria-expanded', 'true')
      await input.press('ArrowDown')
      await input.press('Enter')
      await expect(input).toHaveValue('has:link ')
      await input.fill('has:')
      await input.press('Escape')
      await expect(input).toHaveValue('has:')
      await expect(input).toHaveAttribute('aria-expanded', 'false')
      await input.press('Tab')
      await expect(input).not.toBeFocused()
    })


    test('Approved sender picker: typing, scrolling, keyboard dismissal and draft-only selection', async ({ page }) => {
      await bootDemo(page, '/demo.html?tutorial=false')
      await page.locator('[data-nav="search"]').click()
      const input = page.getByRole('combobox').first()
      await input.fill('design')
      await page.getByRole('button', { name: 'Filtres', exact: true }).click()
      const dialog = page.getByRole('dialog', { name: 'Filtres' })
      const trigger = dialog.getByRole('button', { name: /^De / })
      await trigger.focus()
      await trigger.press('Space')
      const picker = dialog.getByRole('combobox', { name: 'De', exact: true })
      await expect(picker).toBeFocused()
      await picker.fill('nobody-matches-this-name')
      await expect(dialog.getByRole('status')).toHaveText('Aucun expéditeur correspondant')
      const list = dialog.getByRole('listbox')
      await expect(list.getByRole('option')).toHaveCount(2)
      await picker.press('Enter')
      await expect(picker).toBeFocused()
      await expect(input).toHaveValue('design')
      await picker.press('Escape')
      await expect(dialog).toBeVisible()
      await expect(trigger).toHaveText('Tout le monde')
      await expect(trigger).toBeFocused()
      await trigger.press('Enter')
      await expect(picker).toHaveValue('')
      await picker.press('ArrowUp')
      await expect(picker).toBeFocused()
      const activeId = await picker.getAttribute('aria-activedescendant')
      expect(activeId).toBeTruthy()
      const active = page.locator(`[id="${activeId}"]`)
      await expect(active).toBeVisible()
      const scroller = list.locator('[role="presentation"]')
      await expect.poll(() => scroller.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
      const bounds = await scroller.boundingBox()
      const row = await active.boundingBox()
      expect(bounds).not.toBeNull()
      expect(row).not.toBeNull()
      expect(row!.y).toBeGreaterThanOrEqual(bounds!.y)
      expect(row!.y + row!.height).toBeLessThanOrEqual(bounds!.y + bounds!.height + 1)
      await expect(list.getByRole('option', { name: 'Tout le monde', exact: true })).toBeVisible()
      await expect(list.getByRole('option', { name: 'Moi', exact: true })).toBeVisible()
      await picker.press('Tab')
      await expect(dialog.getByLabel('Date', { exact: true })).toBeFocused()
      await expect(trigger).toHaveText('Tout le monde')
      await trigger.click()
      await picker.press('ArrowDown')
      await picker.press('ArrowDown')
      await picker.press('Enter')
      await expect(trigger).toHaveText('Moi')
      await expect(trigger).toBeFocused()
      await expect(page.getByRole('button', { name: 'Retirer Envoyés par moi' })).toHaveCount(0)
      await dialog.getByRole('button', { name: 'Appliquer' }).click()
      await expect(page.getByRole('button', { name: 'Retirer Envoyés par moi' })).toBeVisible()
      await expect(input).toHaveValue('design')
      await expect(input).toBeFocused()

      await page.getByRole('button', { name: 'Filtres', exact: true }).click()
      await dialog.getByRole('button', { name: 'De Moi', exact: true }).press('ArrowDown')
      await picker.fill('Emma')
      await expect(list.getByRole('option').filter({ hasText: 'Emma' }).first()).toBeVisible()
      await list.getByRole('option').filter({ hasText: 'Emma' }).first().click()
      await expect(trigger).toContainText('Emma')
      await page.keyboard.press('Escape')
      await expect(dialog).toHaveCount(0)
      await expect(input).toBeFocused()
      await expect(page.getByRole('button', { name: 'Retirer Envoyés par moi' })).toBeVisible()
    })

  })
}
