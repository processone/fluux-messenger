import { test, expect, type Locator } from '@playwright/test'
import { createInstance } from 'i18next'
import fr from '../apps/fluux/src/i18n/locales/fr.json' with { type: 'json' }
import { bootDemo } from './harness/demoBoot'

const { panel, chip } = fr.search
const t = await createInstance().init({
  lng: 'fr',
  fallbackLng: false,
  resources: { fr: { translation: fr } },
  interpolation: { escapeValue: false },
})
const senderNick = 'Emma'
const senderLabel = `${senderNick} · Team Chat`
const senderTrigger = (dialog: Locator, value: string) => dialog.getByRole('button', { name: `${panel.from} ${value}`, exact: true })
const removeChipName = (label: string) => t('search.chip.remove', { label })
const senderChipName = removeChipName(t('search.chip.from', { name: senderNick }))

for (const viewport of [{ width: 1280, height: 800 }, { width: 390, height: 844 }]) {
  test.describe(`search at ${viewport.width}px`, () => {
    test.use({ viewport, locale: 'fr-FR' })
    test('Filters drafts apply as chips, preserve text, and dismiss with keyboard focus intact', async ({ page }) => {
      await bootDemo(page, '/demo.html?tutorial=false')
      await page.locator('[data-nav="search"]').click()
      const input = page.getByRole('combobox')
      await expect(input).toBeVisible()
      const filters = page.getByRole('button', { name: panel.title, exact: true })
      await expect(filters).toBeVisible()
      await expect(page.getByRole('button', { name: panel.image, exact: true })).toHaveCount(0)
      await input.fill('design')
      await filters.click()
      const dialog = page.getByRole('dialog', { name: panel.title })
      await expect(dialog).toBeVisible()
      await dialog.getByRole('checkbox', { name: panel.image, exact: true }).check()
      await page.keyboard.press('Escape')
      await expect(dialog).toHaveCount(0)
      await expect(input).toHaveValue('design')
      await expect(input).toBeFocused()
      await expect(page.getByRole('button', { name: removeChipName(chip.image), exact: true })).toHaveCount(0)

      await filters.click()
      await expect(dialog.getByRole('checkbox', { name: panel.image, exact: true })).not.toBeChecked()
      await dialog.getByLabel(panel.date, { exact: true }).selectOption('custom')
      await dialog.getByLabel(panel.start).fill('2024-04-01')
      await dialog.getByLabel(panel.end).fill('2024-03-31')
      await expect(dialog.getByRole('alert')).toBeVisible()
      await expect(dialog.getByRole('button', { name: panel.apply })).toBeDisabled()
      await dialog.getByLabel(panel.start).fill('2024-03-01')
      await dialog.getByRole('checkbox', { name: panel.image, exact: true }).check()
      await senderTrigger(dialog, panel.anyone).click()
      await dialog.getByRole('option', { name: panel.me, exact: true }).click()
      await dialog.getByRole('button', { name: panel.apply }).click()
      await expect(dialog).toHaveCount(0)
      await expect(input).toHaveValue('design')
      await expect(page.getByRole('button', { name: removeChipName(chip.mine), exact: true })).toBeVisible()
      await page.getByRole('button', { name: removeChipName(chip.mine), exact: true }).click()
      await expect(page.getByRole('button', { name: removeChipName(chip.image), exact: true })).toBeVisible()
      await page.getByRole('button', { name: removeChipName(chip.image), exact: true }).click()
      await expect(input).toHaveValue('design')

      await input.fill('notes from:')
      const person = page.getByRole('option', { name: `from:${senderNick} ${senderLabel}`, exact: true })
      await expect(person).toBeVisible()
      await person.click()
      await expect(input).toHaveValue('notes')
      const senderChip = page.getByRole('button', { name: senderChipName, exact: true })
      await expect(senderChip).toBeVisible()
      await expect(senderChip).toHaveAccessibleName(new RegExp(`\\b${senderNick}\\b`))

      await input.fill('fr')
      await expect(input).toHaveAttribute('aria-expanded', 'false')
      await input.fill('has:')
      await expect(input).toHaveAttribute('aria-expanded', 'true')
      await input.press('ArrowDown')
      await input.press('Enter')
      await expect(input).toHaveValue('has:link ')
      await input.fill('has:')
      await input.press('Escape')
      await expect(input).toHaveValue('has:')
      await expect(input).toHaveAttribute('aria-expanded', 'false')
      await input.press('Tab')
      await expect(input).not.toBeFocused()
    })

    test('Approved sender picker: typing, scrolling, keyboard dismissal and draft-only selection', async ({ page }) => {
      await bootDemo(page, '/demo.html?tutorial=false')
      await page.locator('[data-nav="search"]').click()
      const input = page.getByRole('combobox').first()
      await input.fill('design')
      await page.getByRole('button', { name: panel.title, exact: true }).click()
      const dialog = page.getByRole('dialog', { name: panel.title })
      const anyoneTrigger = senderTrigger(dialog, panel.anyone)
      await anyoneTrigger.focus()
      await anyoneTrigger.press('Space')
      const picker = dialog.getByRole('combobox', { name: panel.from, exact: true })
      await expect(picker).toBeFocused()
      await picker.fill('nobody-matches-this-name')
      await expect(dialog.getByRole('status')).toHaveText(panel.noSenders)
      const list = dialog.getByRole('listbox')
      await expect(list.getByRole('option')).toHaveCount(2)
      await picker.press('Enter')
      await expect(picker).toBeFocused()
      await expect(input).toHaveValue('design')
      await picker.press('Escape')
      await expect(dialog).toBeVisible()
      await expect(anyoneTrigger).toHaveText(panel.anyone)
      await expect(anyoneTrigger).toBeFocused()
      await anyoneTrigger.press('Enter')
      await expect(picker).toHaveValue('')
      await picker.press('ArrowUp')
      await expect(picker).toBeFocused()
      const activeId = await picker.getAttribute('aria-activedescendant')
      expect(activeId).toBeTruthy()
      const active = page.locator(`[id="${activeId}"]`)
      await expect(active).toBeVisible()
      const scroller = list.locator('[role="presentation"]')
      await expect.poll(() => scroller.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
      const bounds = await scroller.boundingBox()
      const row = await active.boundingBox()
      expect(bounds).not.toBeNull()
      expect(row).not.toBeNull()
      expect(row!.y).toBeGreaterThanOrEqual(bounds!.y)
      expect(row!.y + row!.height).toBeLessThanOrEqual(bounds!.y + bounds!.height + 1)
      const listBounds = await list.boundingBox()
      const formBounds = await dialog.locator('form').boundingBox()
      expect(listBounds).not.toBeNull()
      expect(formBounds).not.toBeNull()
      for (const name of [panel.anyone, panel.me]) {
        const shortcut = await list.getByRole('option', { name, exact: true }).boundingBox()
        expect(shortcut).not.toBeNull()
        expect(shortcut!.y).toBeGreaterThanOrEqual(Math.max(listBounds!.y, formBounds!.y, 0))
        expect(shortcut!.y + shortcut!.height).toBeLessThanOrEqual(Math.min(bounds!.y, formBounds!.y + formBounds!.height, viewport.height))
        expect(shortcut!.x).toBeGreaterThanOrEqual(listBounds!.x)
        expect(shortcut!.x + shortcut!.width).toBeLessThanOrEqual(listBounds!.x + listBounds!.width)
      }
      const bottom = await scroller.evaluate(element => element.scrollTop)
      await page.mouse.move(bounds!.x + 20, bounds!.y + 20)
      // WebKit wheel motion continues after the first changed offset; hover must follow its completion.
      const wheelEnd = await scroller.evaluateHandle(element => ({
        done: new Promise<number>(resolve => {
          element.addEventListener('scrollend', () => resolve(element.scrollTop), { once: true })
        }),
      }))
      await page.mouse.wheel(0, -37)
      const manualScroll = await wheelEnd.evaluate(({ done }) => done)
      await wheelEnd.dispose()
      expect(manualScroll).toBeLessThan(bottom)
      await page.mouse.move(bounds!.x + 24, bounds!.y + 3)
      expect(await scroller.evaluate(element => element.scrollTop)).toBe(manualScroll)
      await picker.press('Tab')
      await expect(dialog.getByLabel(panel.date, { exact: true })).toBeFocused()
      await expect(anyoneTrigger).toHaveText(panel.anyone)
      await anyoneTrigger.click()
      await picker.press('ArrowDown')
      await picker.press('ArrowDown')
      await page.keyboard.down('Enter')
      const meTrigger = senderTrigger(dialog, panel.me)
      await expect(meTrigger).toHaveText(panel.me)
      await page.keyboard.down('Enter')
      await expect(picker).toHaveCount(0)
      await expect(meTrigger).toBeFocused()
      await page.keyboard.up('Enter')
      await meTrigger.press('Enter')
      await expect(picker).toBeFocused()
      await picker.press('Escape')
      await expect(meTrigger).toHaveText(panel.me)
      await expect(meTrigger).toBeFocused()
      await expect(page.getByRole('button', { name: removeChipName(chip.mine), exact: true })).toHaveCount(0)
      await dialog.getByRole('button', { name: panel.apply }).click()
      await expect(page.getByRole('button', { name: removeChipName(chip.mine), exact: true })).toBeVisible()
      await expect(input).toHaveValue('design')
      await expect(input).toBeFocused()

      await page.getByRole('button', { name: panel.title, exact: true }).click()
      await meTrigger.press('ArrowDown')
      await picker.fill(senderNick)
      const sender = list.getByRole('option', { name: senderLabel, exact: true })
      await expect(sender).toBeVisible()
      await sender.click()
      await expect(senderTrigger(dialog, senderLabel)).toHaveText(senderLabel)
      await page.keyboard.press('Escape')
      await expect(dialog).toHaveCount(0)
      await expect(input).toBeFocused()
      await expect(page.getByRole('button', { name: removeChipName(chip.mine), exact: true })).toBeVisible()
    })

    test.describe('short touch-enabled window', () => {
      test.use({ viewport: { width: viewport.width, height: 480 }, hasTouch: true })
      test('Approved controls remain reachable and activate once with the picker open', async ({ page }) => {
        await bootDemo(page, '/demo.html?tutorial=false')
        await page.locator('[data-nav="search"]').click()
        const input = page.getByRole('combobox').first()
        await input.fill('design')
        await page.getByRole('button', { name: panel.title, exact: true }).click()
        const dialog = page.getByRole('dialog', { name: panel.title })
        await senderTrigger(dialog, panel.anyone).tap()
        const picker = dialog.getByRole('combobox', { name: panel.from, exact: true })
        await picker.fill(senderNick)
        await dialog.getByRole('listbox').getByRole('option', { name: senderLabel, exact: true }).tap()
        const selectedSender = senderTrigger(dialog, senderLabel)
        await expect(selectedSender).toHaveText(senderLabel)
        await expect(selectedSender).toBeFocused()
        await selectedSender.tap()
        await dialog.getByLabel(panel.date, { exact: true }).click()
        await expect(dialog.getByLabel(panel.date, { exact: true })).toBeFocused()
        await expect(picker).toBeVisible()
        await dialog.getByRole('checkbox', { name: panel.image, exact: true }).click()
        await expect(dialog.getByRole('checkbox', { name: panel.image, exact: true })).toBeChecked()
        await expect(picker).toBeAttached()
        await dialog.getByRole('button', { name: panel.clear }).click()
        await expect(dialog.getByRole('checkbox', { name: panel.image, exact: true })).not.toBeChecked()
        await expect(dialog.getByRole('option', { name: panel.anyone, exact: true })).toHaveAttribute('aria-selected', 'true')
        await dialog.getByRole('checkbox', { name: panel.image, exact: true }).click()
        const apply = dialog.getByRole('button', { name: panel.apply })
        await apply.scrollIntoViewIfNeeded()
        const applyBounds = await apply.boundingBox()
        const dialogBounds = await dialog.boundingBox()
        expect(applyBounds).not.toBeNull()
        expect(dialogBounds).not.toBeNull()
        expect(applyBounds!.y).toBeGreaterThanOrEqual(dialogBounds!.y)
        expect(applyBounds!.y + applyBounds!.height).toBeLessThanOrEqual(dialogBounds!.y + dialogBounds!.height)
        expect(dialogBounds!.y + dialogBounds!.height).toBeLessThanOrEqual(480)
        await apply.click()
        await expect(dialog).toHaveCount(0)
        await expect(page.getByRole('button', { name: removeChipName(chip.image), exact: true })).toBeVisible()
        await expect(input).toHaveValue('design')
      })
    })

  })
}
